/** WCAG 2.x relative luminance and contrast helpers (hex colours only). */
function channel(value: number) {
  const c = value / 255;
  return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
}

export function luminance(hex: string) {
  const h = hex.replace('#', '');
  const [r, g, b] = [0, 2, 4].map(i => parseInt(h.slice(i, i + 2), 16));
  return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b);
}

export function contrastRatio(a: string, b: string) {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

/** Picks white or near-black text, whichever reads better on the given background. */
export function readableTextOn(background: string) {
  return contrastRatio('#FFFFFF', background) >= contrastRatio('#17152A', background) ? '#FFFFFF' : '#17152A';
}
